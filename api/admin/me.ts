import type { VercelRequest, VercelResponse } from '@vercel/node';
import { verifyAdminIdentity, adminDatabase } from '../_lib/admin-auth.js';
import { createHmac, randomUUID } from 'node:crypto';
import { verifyQueuedTestPayment } from '../_lib/mp-queue-payment-verification.js';

export default async function handler(req: VercelRequest, res: VercelResponse) {
  res.setHeader('Cache-Control', 'no-store');
  if (!(req.method === 'GET' || (req.method === 'POST' && ['webhook_probe', 'webhook_queue_verify'].includes(String(req.query.check))))) {
    res.setHeader('Allow', 'GET, POST');
    return res.status(405).json({ code: 'method_not_allowed' });
  }
  if (!req.headers.authorization?.startsWith('Bearer ')) {
    return res.status(401).json({ code: 'missing_session' });
  }
  try {
    const user = await verifyAdminIdentity(req);
    if (!user) return res.status(403).json({ code: 'not_authorized_admin' });

    if (req.query.check === 'webhook_probe' && req.method === 'POST') {
      if (process.env.VERCEL_ENV !== 'preview') {
        return res.status(403).json({ error: 'Somente Preview' });
      }
      const secret = process.env.MP_WEBHOOK_SECRET?.trim();
      // Always probe the PUBLIC BRANCH ALIAS which Mercado Pago uses, rather
      // than a deployment-specific VERCEL_URL that can require authentication.
      // Never derive a webhook destination from the user-controlled Host header.
      const hostname = 'pulsar-tecnologia-site-git-security-server-api-phase1-qr-flow.vercel.app';
      if (!secret) {
        return res.status(503).json({
          error: 'MP_WEBHOOK_SECRET ausente neste deployment Preview.',
          secretConfigured: false,
          previewUrlConfigured: true
        });
      }
      // Generated by Vercel's Protection Bypass for Automation feature.
      // Never send or return this secret to the browser or include it in URLs.
      const protectionBypass = process.env.VERCEL_AUTOMATION_BYPASS_SECRET?.trim();
      if (!protectionBypass) {
        return res.status(503).json({
          error: 'O bypass automático da Vercel não está configurado neste Preview. Crie a chave em Deployment Protection → Protection Bypass for Automation e faça Redeploy.',
          automationBypassConfigured: false
        });
      }
      const requestId = 'internal-probe-' + randomUUID();
      const timestamp = String(Math.floor(Date.now() / 1000));
      const resourceId = 'diagnostic';
      const manifest = `id:${resourceId};request-id:${requestId};ts:${timestamp};`;
      const digest = createHmac('sha256', secret).update(manifest).digest('hex');
      const response = await fetch('https://' + hostname +
        '/api/mercadopago/webhook?data.id=diagnostic&type=diagnostic', {
        method: 'POST', cache: 'no-store',
        signal: AbortSignal.timeout(10000),
        headers: {
          'Content-Type':'application/json',
          'x-request-id': requestId,
          'x-signature': `ts=${timestamp},v1=${digest}`,
          'x-vercel-protection-bypass': protectionBypass
        },
        body: JSON.stringify({type:'diagnostic',action:'internal.probe',data:{id:resourceId}})
      });
      // A second signed, NON-PAYMENT diagnostic request verifies whether
      // the Supabase Edge Function uses the same webhook secret as Vercel.
      // Never forward the Vercel bypass secret to Supabase.
      let supabaseHttpStatus: number | null = null;
      let supabaseSignatureAccepted = false;
      try {
        const supabaseResponse = await fetch(
          'https://srvctqtmlbkmgiazgsrj.supabase.co/functions/v1/pulsar-mp-test-ingress?data.id=diagnostic&type=diagnostic',
          {
            method: 'POST', cache: 'no-store',
            signal: AbortSignal.timeout(9000),
            headers: {
              'Content-Type': 'application/json',
              'x-request-id': requestId,
              'x-signature': `ts=${timestamp},v1=${digest}`
            },
            body: JSON.stringify({type:'diagnostic',action:'internal.probe',data:{id:resourceId}})
          }
        );
        supabaseHttpStatus = supabaseResponse.status;
        if (supabaseResponse.ok) {
          const check = await supabaseResponse.json().catch(() => null);
          supabaseSignatureAccepted =
            check?.received === true && check?.ignored === true;
        }
      } catch {
        // Network failures are reported as unavailable, never treated as success.
      }
      const contentType = response.headers.get('content-type') || '';
      const vercelAuthRedirect = Boolean(response.headers.get('location')?.includes('vercel.com'));
      let body: Record<string,unknown> = {};
      try {
        if (contentType.includes('application/json')) body = await response.json();
      } catch {}
      const responseLooksLikeVercelProtection =
        !contentType.includes('application/json') &&
        (response.status === 401 || response.status === 403 || vercelAuthRedirect);
      const webhookSignatureAccepted =
        response.ok && body.received === true && body.ignored === true;
      const diag = await adminDatabase().from('pulsar_webhook_diagnostics')
        .select('last_attempt_at,signature_verified')
        .eq('id', 'mp_preview').maybeSingle();
      return res.status(200).json({
        success: webhookSignatureAccepted && !diag.error && diag.data?.signature_verified === true,
        routeHttpStatus: response.status,
        webhookSignatureAccepted,
        supabaseHttpStatus,
        supabaseSignatureAccepted,
        signatureSecretsConsistent: webhookSignatureAccepted && supabaseSignatureAccepted,
        target: 'public_preview_branch_alias',
        responseIsJson: contentType.includes('application/json'),
        possibleVercelProtection: responseLooksLikeVercelProtection,
        automationBypassConfigured: true,
        databaseDiagnosticRecorded: !diag.error && Boolean(diag.data),
        databaseDiagnosticSignatureVerified: diag.data?.signature_verified === true,
        diagnosticDbErrorCode: diag.error?.code || null,
        message: webhookSignatureAccepted
          ? 'Webhook autenticou a notificação fictícia via URL pública do Preview.'
          : responseLooksLikeVercelProtection
            ? 'Possível Vercel Deployment Protection: resposta 401/403 não JSON antes do webhook.'
            : 'A rota do webhook respondeu, mas não validou o autoteste. Consulte HTTP e diagnóstico.'
      });
    }

    // Protected, read-only access to the latest preview webhook signature
    // rejection. Exposes no identifiers, signatures, tokens or customer data.
    if (req.query.check === 'webhook') {
      if (process.env.VERCEL_ENV !== 'preview') {
        return res.status(403).json({ error: 'Somente Preview.' });
      }
      const { data, error } = await adminDatabase()
        .from('pulsar_webhook_diagnostics')
        .select('last_attempt_at,signature_header_present,request_id_header_present,query_data_id_present,body_data_id_present,signature_format_valid,signature_verified')
        .eq('id', 'mp_preview').maybeSingle();
      if (error) return res.status(503).json({
        error: 'Diagnóstico indisponível. Verifique a migração de diagnóstico.'
      });
      return res.status(200).json({
        recorded: Boolean(data),
        diagnostics: data || null,
        message: data
          ? 'Última tentativa POST recebida pelo webhook. Nenhuma credencial é exibida.'
          : 'Nenhuma tentativa POST registrada nesta versão; verifique a URL de destino e a entrega da notificação.'
      });
    }

    // Read-only verification of ONE queued event against Mercado Pago test
    // credentials. No updates to orders or queue; simulated IDs fail closed.
    if (req.query.check === 'webhook_queue_verify' && req.method === 'POST') {
      if (process.env.VERCEL_ENV !== 'preview') {
        return res.status(403).json({ error: 'Somente Preview.' });
      }
      const token = process.env.MERCADO_PAGO_TEST_ACCESS_TOKEN?.trim();
      const sellerId = process.env.PULSAR_MP_TEST_SELLER_ID;
      const buyerId = process.env.PULSAR_MP_TEST_BUYER_ID;
      if (process.env.PULSAR_ENABLE_MP_TEST_CHECKOUT !== 'true' ||
          !token || !/^\d{6,24}$/.test(sellerId || '') ||
          !/^\d{6,24}$/.test(buyerId || '')) {
        return res.status(503).json({ error: 'Ambiente de pagamento de teste incompleto.' });
      }
      const db = adminDatabase();
      const { data: queued, error: inboxError } = await db
        .from('pulsar_mp_test_webhook_inbox')
        .select('resource_id,event_type,process_status')
        .eq('process_status', 'queued')
        .order('received_at', { ascending: false })
        .limit(1);
      if (inboxError) return res.status(503).json({ error: 'Fila de testes indisponível.' });
      if (!queued?.length) return res.status(200).json({
        checked: true, verified: false, reason: 'empty_queue',
        message: 'Nenhuma notificação pendente para verificar.'
      });
      const id = String(queued[0].resource_id);
      if (queued[0].event_type !== 'payment' || !/^\d{1,24}$/.test(id)) {
        return res.status(200).json({ checked:true, verified:false,
          reason:'invalid_queued_event', message:'Evento inválido; nenhum pedido alterado.' });
      }
      const headers = { Authorization: 'Bearer ' + token, Accept: 'application/json' };
      const getProvider = (url: string) => fetch(url, {
        headers, cache: 'no-store', signal: AbortSignal.timeout(7000)
      });
      const [paymentResponse, sellerResponse] = await Promise.all([
        getProvider('https://api.mercadopago.com/v1/payments/' + id),
        getProvider('https://api.mercadolibre.com/users/me')
      ]);
      if (!paymentResponse.ok || !sellerResponse.ok) return res.status(200).json({
        checked:true, verified:false, reason:'provider_not_verified',
        message:'O Mercado Pago não confirmou o ID da fila; nenhum pedido alterado.'
      });
      const payment = await paymentResponse.json();
      const seller = await sellerResponse.json();
      const reference = typeof payment.external_reference === 'string'
        ? payment.external_reference : '';
      if (!/^PLS-[0-9A-F]{24}$/.test(reference) ||
          !/^\d{1,24}$/.test(String(payment.order?.id ?? ''))) {
        return res.status(200).json({
          checked:true, verified:false, reason:'invalid_payment_reference',
          message:'Pagamento sem vínculo verificável; nenhum pedido alterado.'
        });
      }
      const found = await db.from('orders')
        .select('order_number,total_amount,payment_status,mercado_pago_preference_id,mercado_pago_payment_id')
        .eq('order_number',reference).maybeSingle();
      if (found.error) return res.status(503).json({ error:'Falha ao consultar pedido.' });
      const merchantResponse = await getProvider(
        'https://api.mercadopago.com/merchant_orders/' + String(payment.order.id)
      );
      if (!merchantResponse.ok) return res.status(200).json({
        checked:true, verified:false, reason:'merchant_order_unavailable',
        message:'Pedido comercial não verificado; nenhum pedido alterado.'
      });
      const merchantOrder = await merchantResponse.json();
      const result = verifyQueuedTestPayment({
        paymentId:id, payment, seller, merchantOrder, order:found.data,
        sellerId, buyerId, testToken:token
      });
      return res.status(200).json({
        checked:true, verified:result.verified, reason:result.reason,
        message:result.verified
          ? 'Pagamento de teste verificável. Consulta apenas leitura; nenhum pedido alterado.'
          : 'Notificação não corresponde a um pagamento de teste validado. Nenhum pedido alterado.'
      });
    }

    // Preview-only and admin-only inbox health: never expose payment IDs,
    // order details or customer data. This does not process any payment.
    if (req.query.check === 'webhook_inbox') {
      if (process.env.VERCEL_ENV !== 'preview') {
        return res.status(403).json({ error: 'Somente Preview.' });
      }
      const { data, error } = await adminDatabase()
        .from('pulsar_mp_test_webhook_inbox')
        .select('process_status,received_at')
        .order('received_at', { ascending: false })
        .limit(100);
      if (error) return res.status(503).json({ error: 'Fila de notificações indisponível.' });
      const rows = data || [];
      return res.status(200).json({
        checked: true,
        recentCount: rows.length,
        queuedCount: rows.filter(row => row.process_status === 'queued').length,
        latestReceivedAt: rows[0]?.received_at || null,
        limitedToLatest: 100,
        message: rows.length
          ? 'Notificações assinadas registradas na fila de teste; nenhum pedido foi aprovado por esta consulta.'
          : 'Nenhuma notificação de pagamento chegou à fila de teste ainda.'
      });
    }

    // Read-only checkout readiness diagnostics. Reuse the existing admin
    // endpoint instead of adding another Vercel function.
    if (req.query.check === 'checkout') {
      const db = adminDatabase();
      const schema = await db.from('orders')
        .select('checkout_idempotency_key,mercado_pago_preference_id,shipping_service_id').limit(0);
      const checks = {
        previewDeployment: process.env.VERCEL_ENV === 'preview',
        mercadoPagoTokenConfigured: Boolean(process.env.MERCADO_PAGO_ACCESS_TOKEN?.trim()),
        webhookSecretConfigured: Boolean(process.env.MP_WEBHOOK_SECRET?.trim()),
        melhorEnvioTokenConfigured: Boolean(process.env.MELHOR_ENVIO_TOKEN?.trim()),
        shippingOriginConfigured: /^\d{8}$/.test((process.env.SHIPPING_ORIGIN_CEP || '').replace(/\D/g,'')),
        shippingSandboxEnabled: process.env.MELHOR_ENVIO_SANDBOX === 'true',
        idempotencySchemaPrepared: !schema.error,
        paymentPreferenceFlowVerified: false,
        webhookOrderAssociationVerified: false,
        productionRlsCutoverVerified: false
      };
      return res.status(200).json({
        readyForPayments: false, checks,
        message: 'Diagnóstico somente leitura. Nenhum pedido, pagamento ou mudança de permissão foi realizado.'
      });
    }

    // A successful login is separate from privileged catalog/database access.
    // Verify server credentials without exposing the key or any table rows.
    let adminApiReady = false;
    let adminApiDiagnostic = 'not_configured';
    if (process.env.SUPABASE_SERVICE_ROLE_KEY) {
      try {
        const { error } = await adminDatabase().from('products').select('id').limit(1);
        adminApiReady = !error;
        adminApiDiagnostic = error ? 'database_access_rejected' : 'ok';
      } catch {
        adminApiDiagnostic = 'server_credentials_invalid';
      }
    }
    return res.status(200).json({
      authenticated: true,
      userId: user.id,
      adminApiReady,
      adminApiDiagnostic
    });
  } catch (err) {
    console.error('Pulsar admin auth: identity verification failed', {
      name: err instanceof Error ? err.name : 'Unknown'
    });
    return res.status(503).json({ code: 'server_auth_provider_error' });
  }
}
